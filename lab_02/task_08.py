n = int(input("Количество заданий (10–40): "))

# У 11–19 всегда «заданий», даже когда последняя цифра похожа на исключение.
teens = (
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать",
)
tens = ("двадцать", "тридцать", "сорок")
units = ("", "одно", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")
last_digit = n % 10

if n < 20:
    number = teens[n - 10]
    ending = "учебных заданий"
else:
    number = tens[n // 10 - 2]
    if last_digit != 0:
        number += " " + units[last_digit]

    if last_digit == 1:
        ending = "учебное задание"
    elif 2 <= last_digit <= 4:
        ending = "учебных задания"
    else:
        ending = "учебных заданий"

print(number, ending)
