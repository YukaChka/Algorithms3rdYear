year = int(input("Год: "))

# По условию цвет меняется после каждого 12-летнего подцикла.
position = (year - 1984) % 60
color_index = position // 12
animal_index = position % 12

# Остаток от деления на 60 возвращает год внутрь цикла.
animals = (
    "крысы", "коровы", "тигра", "зайца", "дракона", "змеи",
    "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи",
)
if 2 <= animal_index <= 4:
    colors = ("зеленого", "красного", "желтого", "белого", "черного")
else:
    colors = ("зеленой", "красной", "желтой", "белой", "черной")

print("год", colors[color_index], animals[animal_index])
