n = int(input("Число от 100 до 999: "))

# Остаток после сотен читаем отдельно: 14 — одно слово, 54 — два.
hundreds = (
    "сто", "двести", "триста", "четыреста", "пятьсот",
    "шестьсот", "семьсот", "восемьсот", "девятьсот",
)
teens = (
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать",
)
tens = ("двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
        "семьдесят", "восемьдесят", "девяносто")
units = ("один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")

parts = [hundreds[n // 100 - 1]]
remainder = n % 100
if 10 <= remainder <= 19:
    parts.append(teens[remainder - 10])
else:
    if remainder >= 20:
        parts.append(tens[remainder // 10 - 2])
    if remainder % 10 != 0:
        parts.append(units[remainder % 10 - 1])

print(" ".join(parts))
