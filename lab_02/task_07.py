day = int(input("Номер дня (1–31): "))
month = int(input("Номер месяца (1–12): "))

# У месяца свой список, а у «двадцать первого» меняется только последнее слово.
days = (
    "первое", "второе", "третье", "четвертое", "пятое", "шестое",
    "седьмое", "восьмое", "девятое", "десятое", "одиннадцатое",
    "двенадцатое", "тринадцатое", "четырнадцатое", "пятнадцатое",
    "шестнадцатое", "семнадцатое", "восемнадцатое", "девятнадцатое",
    "двадцатое",
)
months = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)

if day <= 20:
    day_text = days[day - 1]
elif day < 30:
    day_text = "двадцать " + days[day - 21]
elif day == 30:
    day_text = "тридцатое"
else:
    day_text = "тридцать первое"

print(day_text, months[month - 1])
