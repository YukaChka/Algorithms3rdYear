a = float(input("Первое ненулевое число: "))
b = float(input("Второе ненулевое число: "))

# Знак снимаем до всех операций. У разности модулей он всё равно может появиться.
a_abs = abs(a)
b_abs = abs(b)

print("Сумма модулей:", a_abs + b_abs)
print("Разность модулей:", a_abs - b_abs)
print("Произведение модулей:", a_abs * b_abs)
print("Частное модулей:", a_abs / b_abs)
